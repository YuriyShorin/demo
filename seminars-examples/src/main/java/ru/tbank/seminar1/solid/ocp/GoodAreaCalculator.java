package ru.tbank.seminar1.solid.ocp;

/**
 * ХОРОШО: принцип открытости/закрытости соблюдён.
 *
 * <p>Калькулятор зависит только от абстракции {@link Shape} и полиморфно вызывает
 * {@code area()}. Добавление новой фигуры (например, {@code Triangle}) выполняется
 * написанием НОВОГО класса, реализующего {@link Shape}, — калькулятор и все существующие
 * фигуры остаются нетронутыми.
 *
 * <p>Открыт для расширения (новые фигуры), закрыт для модификации (ничего существующего не меняется).
 */
public class GoodAreaCalculator {

    public double area(Shape shape) {
        return shape.area();
    }
}