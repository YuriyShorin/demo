package ru.tbank.seminar1.solid.isp;

/**
 * ПЛОХО: нарушен принцип разделения интерфейсов (ISP).
 *
 * <p>Этот «жирный» интерфейс вынуждает каждого работника реализовывать все три метода,
 * даже когда они не нужны. {@code Robot} не может есть, а {@code Human} не может заряжаться —
 * но оба обязаны предоставить эти методы, обычно как некрасивые заглушки, бросающие
 * {@code UnsupportedOperationException}.
 *
 * <p>Клиент, зависящий от этого интерфейса, связан с возможностями, которые он никогда не использует.
 */
public interface BadWorker {

    void work();

    void eat();

    void charge();
}